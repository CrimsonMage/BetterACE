pub(crate) fn resolve(family: &str, name: &str) -> Option<u32> {
    match family {
        "PropertyInt" => crate::integer_property_names::propertyint(name),
        "PropertyBool" => propertybool(name),
        "PropertyDataId" => propertydataid(name),
        "PropertyFloat" => propertyfloat(name),
        "PropertyInstanceId" => propertyinstanceid(name),
        "PropertyInt64" => propertyint64(name),
        "PropertyString" => propertystring(name),
        "PositionType" => positiontype(name),
        "PropertyAttribute" => propertyattribute(name),
        "PropertyAttribute2nd" => propertyattribute2nd(name),
        "CombatBodyPart" => combatbodypart(name),
        "Skill" => skill(name),
        _ => None,
    }
}

