#!/usr/bin/env python3
"""Extract pinned ACE chat-window enums into tests/fixtures/spewbox_enums.csv.

Parses the explicit members of WeenieError, WeenieErrorWithString and ChatMessageType
from the pinned ACE snapshot. Output is deterministic (no timestamps, source order).
Every source file is hashed in the CSV header. Run with: python3 -I <this file>
"""
from pathlib import Path
import hashlib
import re
import sys

PIN = "47edade3bd3f6044b676d4eb877c4965c7eda62b"
ROOT = Path(__file__).resolve().parents[4]
ENUM_DIR = ROOT / ".reference" / f"ACE-{PIN}" / "Source" / "ACE.Entity" / "Enum"
OUT = Path(__file__).resolve().parent.parent / "tests" / "fixtures" / "spewbox_enums.csv"

# (enum name, source file, expected member count, expected C# base type)
ENUMS = [
    ("WeenieError", "WeenieError.cs", 369, "int"),
    ("WeenieErrorWithString", "WeenieErrorWithString.cs", 113, "int"),
    ("ChatMessageType", "ChatMessageType.cs", 31, "uint"),
]

HEADER_RE = re.compile(r"^\s*public enum (\w+)\s*(?::\s*(\w+))?\s*$")
MEMBER_RE = re.compile(r"^\s+([A-Za-z_]\w*)\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*,?\s*$")


def members(text: str, enum: str, base: str, expected: int):
    lines = text.splitlines()
    start = None
    for i, line in enumerate(lines):
        m = HEADER_RE.match(line)
        if m and m.group(1) == enum:
            start = i
            declared_base = m.group(2) or "int"
            break
    if start is None:
        sys.exit(f"enum {enum} not found")
    if declared_base != base:
        sys.exit(f"enum {enum} base type is {declared_base}, expected {base}")
    out = []
    for line in lines[start + 1:]:
        if line.startswith("    }"):
            break
        stripped = line.strip()
        if stripped.startswith("//") or not stripped:
            continue
        m = MEMBER_RE.match(line)
        if not m:
            continue
        literal = m.group(2)
        value = int(literal, 16) if literal.lower().startswith("0x") else int(literal)
        out.append((m.group(1), value))
    if len(out) != expected:
        sys.exit(f"enum {enum}: {len(out)} members, expected {expected}")
    names = [n for n, _ in out]
    values = [v for _, v in out]
    if len(set(names)) != len(names):
        sys.exit(f"enum {enum}: duplicate member name")
    if len(set(values)) != len(values):
        sys.exit(f"enum {enum}: duplicate member value")
    if any(v < 0 or v > 0xFFFFFFFF for v in values):
        sys.exit(f"enum {enum}: value outside u32")
    return out


def main() -> None:
    rows = []
    hashes = []
    for enum, filename, expected, base in ENUMS:
        path = ENUM_DIR / filename
        data = path.read_bytes()
        hashes.append(f"# Source/ACE.Entity/Enum/{filename} sha256={hashlib.sha256(data).hexdigest()}")
        for name, value in members(data.decode("utf-8"), enum, base, expected):
            rows.append(f"{enum},{name},{value}")
    header = [
        f"# Official ACEmulator/ACE {PIN}; AGPL-3.0-only; ACE contributors",
        "# Generated by crates/network/bace-wire/oracle/spewbox_enums_generate.py",
        "# Explicit members only, source order. WeenieError/WeenieErrorWithString are C# int, ChatMessageType is uint.",
        *hashes,
        "enum,name,value",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(header + rows) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(rows)} rows to {OUT}")


if __name__ == "__main__":
    main()
